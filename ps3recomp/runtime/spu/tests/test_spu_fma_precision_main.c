/*
 * TDD: gate PS3_SPU_FMA_ISA para a familia single-precision inteira do SPU --
 * spu_fa/spu_fs/spu_fm E os fundidos spu_fma/spu_fms/spu_fnms
 * (runtime/spu/spu_helpers.h) -- ver o comentario acima de spu_fma_isa_gate()
 * no header para o porque' (round-toward-zero + flush-to-zero de resultado E de
 * operando subnormal, sem fesetround, por causa da isolacao de jobs SPU via
 * sigaltstack/siglongjmp; e error-free transform two_sum para evitar
 * double-rounding no arredondamento final).
 *
 * Este binario e' compilado UMA vez mas corre-se DUAS vezes (ver
 * run_tests.sh), com environments diferentes:
 *
 *   sem PS3_SPU_FMA_ISA (unset)  -> bateria de REGRESSAO (gate desligado):
 *     confirma que o comportamento DEFAULT de hoje -- round-to-nearest
 *     simples `a*b+c` em float nativo -- fica byte-a-byte identico depois
 *     desta mudanca. E' a guarda contra qualquer refactor acidental do
 *     caminho default.
 *
 *   PS3_SPU_FMA_ISA=1            -> bateria de PRECISAO (gate ligado):
 *     vetores de fronteira onde o arredondamento truncado diverge do
 *     round-to-nearest (com e sem carry para o expoente), mais flush-to-zero
 *     de subnormal e saturacao de overflow.
 *
 * O main() le a MESMA env var (getenv) para escolher a bateria -- nao ha
 * hook de override so' para teste: como as env vars nao mudam durante a
 * vida de um processo, ler a variavel aqui e' garantido dar o mesmo
 * resultado booleano que o cache interno de spu_fma_isa_gate() vai dar
 * quando spu_fma/fms/fnms forem chamados mais abaixo, no MESMO processo.
 *
 * Os vetores de fronteira usam produtos EXATOS (a,b potencia de 2 ou com
 * poucos bits de mantissa) para que o resultado nao dependa de
 * -ffp-contract (fusao do multiply+add pelo compilador): se a*b nao tem
 * erro de arredondamento nenhum, computa-lo fundido ou em dois passos da'
 * exatamente o mesmo double antes do passo final de arredondamento para
 * float -- o teste fica robusto a qualquer nivel de otimizacao.
 *
 * Build: gcc -std=c11 -I../.. test_spu_fma_precision_main.c -o test_spu_fma_precision
 */
#include "../spu_helpers.h"
#include "spu_fma_precision_vectors.h"   /* AUTO-GENERATED by gen_test_spu_fma_precision.py */
#include <stdio.h>
#include <string.h>
#include <math.h>
#include <float.h>
#include <stdlib.h>

static int g_pass = 0, g_fail = 0;
static const char* g_current = "(none)";
#define TEST(name) g_current = name

static u128 f32x4(float v) { u128 r; r._f32[0]=r._f32[1]=r._f32[2]=r._f32[3]=v; return r; }
static u128 u32x4(uint32_t b) { u128 r; r._u32[0]=r._u32[1]=r._u32[2]=r._u32[3]=b; return r; }

static uint32_t f32_bits(float f) { uint32_t u; memcpy(&u, &f, sizeof u); return u; }

/* Bit-exact compare (not `==`) so signed zero and NaN payloads are honoured. */
static void expect_f32(u128 got, float expected) {
    uint32_t e = f32_bits(expected);
    int ok = 1;
    for (int i = 0; i < 4; i++) if (f32_bits(got._f32[i]) != e) ok = 0;
    if (ok) { g_pass++; return; }
    g_fail++;
    fprintf(stderr, "FAIL: %s\n", g_current);
    for (int i = 0; i < 4; i++)
        fprintf(stderr, "  lane %d: got %08X (%.9g) expected %08X (%.9g)\n",
                i, f32_bits(got._f32[i]), (double)got._f32[i], e, (double)expected);
}

/* Bit-exact compare against a raw uint32 float pattern (all 4 lanes). */
static void expect_bits(u128 got, uint32_t e) {
    int ok = 1;
    for (int i = 0; i < 4; i++) if (f32_bits(got._f32[i]) != e) ok = 0;
    if (ok) { g_pass++; return; }
    g_fail++;
    fprintf(stderr, "FAIL: %s\n", g_current);
    for (int i = 0; i < 4; i++)
        fprintf(stderr, "  lane %d: got %08X (%.9g) expected %08X\n",
                i, f32_bits(got._f32[i]), (double)got._f32[i], e);
}

/* Drive one generated vector (gate-on semantics). */
static void run_vector(const spu_fma_vec_t* v) {
    u128 va = u32x4(v->a), vb = u32x4(v->b), vc = u32x4(v->c);
    u128 got;
    if      (!strcmp(v->op, "fma"))  got = spu_fma(va, vb, vc);
    else if (!strcmp(v->op, "fms"))  got = spu_fms(va, vb, vc);
    else if (!strcmp(v->op, "fnms")) got = spu_fnms(va, vb, vc);
    else if (!strcmp(v->op, "fa"))   got = spu_fa(va, vb);
    else if (!strcmp(v->op, "fs"))   got = spu_fs(va, vb);
    else if (!strcmp(v->op, "fm"))   got = spu_fm(va, vb);
    else { g_fail++; fprintf(stderr, "FAIL: unknown op %s\n", v->op); return; }
    char nm[160];
    snprintf(nm, sizeof nm, "gate-on vector [%s] %s", v->op, v->name);
    TEST(nm);
    expect_bits(got, v->expected);
}

/* ---------------------------------------------------------------------------
 * Bateria (a): guarda de regressao -- gate desligado (default).
 * ------------------------------------------------------------------------*/
static void run_regression_gate_off(void) {
    struct { float a, b, c; } v[] = {
        {   2.0f,     3.0f,    1.0f  },
        {  -2.5f,     4.0f,   -1.25f },
        {   0.1f,     0.2f,    0.3f  },
        {   1e20f,    1e20f,   1.0f  },   /* overflow-ish -- gate-off e' so' o float nativo */
        {  -0.0f,     5.0f,    0.0f  },
        { 123.456f, -789.012f, 0.5f  },
        /* mesmos inputs dos vetores de fronteira da bateria (b) -- aqui so'
         * confirmamos que o DEFAULT continua igual ao float nativo. */
        {   1.0f,     1.0f,    0x1.8p-24f },
    };
    for (size_t i = 0; i < sizeof(v)/sizeof(v[0]); i++) {
        float a = v[i].a, b = v[i].b, c = v[i].c;
        u128 va = f32x4(a), vb = f32x4(b), vc = f32x4(c);

        char name[80];
        snprintf(name, sizeof name, "gate-off regression #%zu (fma)", i);
        TEST(name); expect_f32(spu_fma(va, vb, vc), a*b+c);
        snprintf(name, sizeof name, "gate-off regression #%zu (fms)", i);
        TEST(name); expect_f32(spu_fms(va, vb, vc), a*b-c);
        snprintf(name, sizeof name, "gate-off regression #%zu (fnms)", i);
        TEST(name); expect_f32(spu_fnms(va, vb, vc), c-a*b);
        /* fa/fs/fm are also gated now (whole SP family), so guard their
         * gate-off default too: must stay byte-identical to native float. */
        snprintf(name, sizeof name, "gate-off regression #%zu (fa)", i);
        TEST(name); expect_f32(spu_fa(va, vb), a+b);
        snprintf(name, sizeof name, "gate-off regression #%zu (fs)", i);
        TEST(name); expect_f32(spu_fs(va, vb), a-b);
        snprintf(name, sizeof name, "gate-off regression #%zu (fm)", i);
        TEST(name); expect_f32(spu_fm(va, vb), a*b);
    }
}

/* ---------------------------------------------------------------------------
 * Bateria (b): PS3_SPU_FMA_ISA=1 -- vetores de fronteira.
 * ------------------------------------------------------------------------*/
static void run_precision_gate_on(void) {
    /* ---- (0) vetores gerados por gen_test_spu_fma_precision.py ----
     * Expected vem de aritmetica EXATA (Fraction) para todos os nao-nulos,
     * incluindo os casos adversariais de double-rounding onde a abordagem
     * ingenua `(double)a*b + (double)c` diverge do round-toward-zero correto.
     * Cobre fma/fms/fnms/fa/fs/fm e flush de operando subnormal. */
    for (int i = 0; i < SPU_FMA_VECTORS_N; i++)
        run_vector(&SPU_FMA_VECTORS[i]);

    /* ---- (1) fronteira aditiva, sem carry para o expoente ----
     * a=b=1 -> produto exato 1.0. c = 1.5*2^-24 (representavel exato como
     * float: so' precisa de 1 bit de mantissa). soma exata = 1 + 0.75*ULP
     * (ULP em [1,2) = 2^-23) -> round-to-nearest arredonda para CIMA
     * (nextafter(1.0f)); round-toward-zero trunca para 1.0f. */
    {
        float a = 1.0f, b = 1.0f, c = 0x1.8p-24f; /* 1.5 * 2^-24 */
        u128 va = f32x4(a), vb = f32x4(b), vc = f32x4(c);
        TEST("gate-on: fma additive boundary (no exponent carry)");
        expect_f32(spu_fma(va, vb, vc), 1.0f);
        TEST("gate-on: fms additive boundary (no exponent carry)");
        expect_f32(spu_fms(va, vb, f32x4(-c)), 1.0f);
        TEST("gate-on: fnms additive boundary (no exponent carry)");
        expect_f32(spu_fnms(f32x4(1.0f), f32x4(-1.0f), vc), 1.0f);
    }

    /* ---- (2) fronteira multiplicativa, COM carry para o expoente ----
     * a=1+2^-13, b=1-2^-13 -> produto exato = 1 - 2^-26 (diferenca de
     * quadrados). Isso cai a meio entre float(1-2^-24) [truncado] e
     * float(1.0) [arredondado para cima, com carry de mantissa 0x7FFFFF ->
     * 0x800000 subindo o expoente]. Prova que o truncamento manual nunca
     * arredonda para cima mesmo quando o valor nativo faria carry. */
    {
        float a = 1.0f + 0x1p-13f, b = 1.0f - 0x1p-13f;
        u128 va = f32x4(a), vb = f32x4(b), vc = f32x4(0.0f);
        float rtz_expected = 1.0f - 0x1p-24f; /* maior float abaixo de 1.0 */
        TEST("gate-on: fma multiplicative boundary (exponent-carry avoided)");
        expect_f32(spu_fma(va, vb, vc), rtz_expected);
        TEST("gate-on: fnms multiplicative boundary (sign flip, same carry)");
        expect_f32(spu_fnms(va, vb, vc), -rtz_expected);
    }

    /* ---- (3) flush-to-zero de subnormal ----
     * produto = 2^-140, muito abaixo do menor float normal (2^-126) ->
     * sem suporte a subnormais no pipe single-precision do SPU -> 0
     * (com sinal preservado). */
    {
        float a = 0x1p-70f, b = 0x1p-70f;
        u128 va = f32x4(a), vb = f32x4(b), vc = f32x4(0.0f);
        TEST("gate-on: fma denormal flush-to-zero (+0)");
        expect_f32(spu_fma(va, vb, vc), 0.0f);
        TEST("gate-on: fnms denormal flush-to-zero (-0, sinal preservado)");
        expect_f32(spu_fnms(va, vb, vc), -0.0f);
    }

    /* ---- (4) saturacao de overflow (nunca produz +-inf) ---- */
    {
        u128 va = f32x4(FLT_MAX), vb = f32x4(2.0f), vc = f32x4(0.0f);
        TEST("gate-on: fma overflow saturates to +FLT_MAX (not +inf)");
        expect_f32(spu_fma(va, vb, vc), FLT_MAX);
        TEST("gate-on: fnms overflow saturates to -FLT_MAX (not -inf)");
        expect_f32(spu_fnms(va, vb, vc), -FLT_MAX);
    }
}

int main(void) {
    /* Read the gate exactly like spu_fma_isa_gate() does (repo convention:
     * "0" disables, only a non-empty non-"0" value enables) so this harness
     * picks the same battery the gated helpers will actually run. */
    const char* ge = getenv("PS3_SPU_FMA_ISA");
    int gate_on = (ge && ge[0] && ge[0] != '0') ? 1 : 0;

    if (gate_on) run_precision_gate_on();
    else         run_regression_gate_off();

    fprintf(stderr, "\n%s (%s): %d passed, %d failed\n",
            g_fail ? "RED" : "GREEN", gate_on ? "gate=ON" : "gate=OFF", g_pass, g_fail);
    return g_fail ? 1 : 0;
}
